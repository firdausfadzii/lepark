export function resolveSpaceAssetShopTheme(options: {
  shopTheme?: string | null;
  spaceName?: string | null;
  focusTheme?: string | null;
  tiles?: Record<string, string> | null;
}): ResolvedAssetShopTheme {
  if (
    options.shopTheme === "office" ||
    options.shopTheme === "pet_shop" ||
    options.shopTheme === "guild" ||
    options.shopTheme === "restaurant" ||
    options.shopTheme === "living_room" ||
    options.shopTheme === "all"
  ) {
    return options.shopTheme;
  }

  const nameLower = (options.spaceName || "").toLowerCase();
  if (/\b(restaurant|bistro|diner|eatery|saffron)\b/.test(nameLower)) {
    return "restaurant";
  }
  if (options.tiles && typeof options.tiles === "object") {
    let restaurantCount = 0;
    for (const raw of Object.values(options.tiles)) {
      if (typeof raw === "string" && raw.includes("restaurant/")) {
        restaurantCount++;
        if (restaurantCount >= 2) return "restaurant";
      }
    }
  }

  const focusResolved = resolveSpaceFocusTheme({
    spaceName: options.spaceName,
    focusTheme: options.focusTheme,
    tiles: options.tiles,
    fallbackTheme: "park",
  });

  if (
    focusResolved === "office" ||
    focusResolved === "pet_shop" ||
    focusResolved === "guild" ||
    focusResolved === "living_room"
  ) {
    return focusResolved;
  }

  return "general";
}

export function getSellerThemeProfile(resolvedTheme: ResolvedAssetShopTheme): SellerThemeProfile {
  return SELLER_THEME_PROFILES[resolvedTheme] || SELLER_THEME_PROFILES.general;
}

export interface SpaceShopCatalogItem {
  assetId: string;
  name: string;
  groupId: PaidAssetPackId;
  groupLabel: string;
  category: "decoration" | "floor";
  cost: number;
}

export interface SpaceShopCatalogGroup {
  id: PaidAssetPackId;
  label: string;
  category: "decoration" | "floor";
  items: SpaceShopCatalogItem[];
}

export interface SpaceShopCatalog {
  resolvedTheme: ResolvedAssetShopTheme;
  profile: SellerThemeProfile;
  groups: SpaceShopCatalogGroup[];
  assetIds: string[];
  totalCount: number;
}

export function getSpaceShopCatalog(options: {
  shopTheme?: string | null;
  spaceName?: string | null;
  category?: string | null;
  focusTheme?: string | null;
  tiles?: Record<string, string> | null;
}): SpaceShopCatalog {
  const resolvedTheme = resolveSpaceAssetShopTheme(options);
  const profile = getSellerThemeProfile(resolvedTheme);
  const allowedIds = new Set<PaidAssetPackId>(profile.groupIds);

  const groups: SpaceShopCatalogGroup[] = [];
  const assetIds: string[] = [];

  for (const groupMeta of PAID_ASSET_GROUPS) {
    if (!allowedIds.has(groupMeta.id)) continue;
    const items: SpaceShopCatalogItem[] = groupMeta.items.map((name) => {
      const assetId = `${groupMeta.prefix}/${name}`;
      assetIds.push(assetId);
      return {
        assetId,
        name,
        groupId: groupMeta.id,
        groupLabel: groupMeta.label,
        category: groupMeta.category,
        cost: ASSET_UNLOCK_COST,
      };
    });
    groups.push({
      id: groupMeta.id,
      label: groupMeta.label,
      category: groupMeta.category,
      items,
    });
  }

  return {
    resolvedTheme,
    profile,
    groups,
    assetIds,
    totalCount: assetIds.length,
  };
}

export function isAssetSoldInShopTheme(
  assetId: string,
  resolvedTheme: ResolvedAssetShopTheme
): boolean {
  if (!assetId) return false;
  const profile = getSellerThemeProfile(resolvedTheme);
  if (profile.groupIds.length === 0) return false;
  return profile.groupIds.some((prefix) => assetId.startsWith(`${prefix}/`));
}
